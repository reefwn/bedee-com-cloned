type TextNode = {
  type: 'text'
  mode: 'normal'
  text: string
  detail: number
  format: number
  style: string
  version: 1
}

const BOLD = 1

function t(text: string, bold = false): TextNode {
  return { type: 'text', mode: 'normal', text, detail: 0, format: bold ? BOLD : 0, style: '', version: 1 }
}

function paragraph(children: TextNode[]) {
  return {
    type: 'paragraph' as const,
    children,
    direction: 'ltr' as const,
    format: '' as const,
    indent: 0,
    version: 1 as const,
    textFormat: 0,
    textStyle: '',
  }
}

function heading(tag: 'h2' | 'h3', children: TextNode[]) {
  return {
    type: 'heading' as const,
    tag,
    children,
    direction: 'ltr' as const,
    format: '' as const,
    indent: 0,
    version: 1 as const,
  }
}

function listItem(children: TextNode[], value: number) {
  return {
    type: 'listitem' as const,
    value,
    children,
    direction: 'ltr' as const,
    format: '' as const,
    indent: 0,
    version: 1 as const,
  }
}

function list(items: TextNode[][], ordered = false) {
  return {
    type: 'list' as const,
    tag: (ordered ? 'ol' : 'ul') as 'ol' | 'ul',
    listType: (ordered ? 'number' : 'bullet') as 'number' | 'bullet',
    start: 1,
    direction: 'ltr' as const,
    format: '' as const,
    indent: 0,
    version: 1 as const,
    children: items.map((children, i) => listItem(children, i + 1)),
  }
}

