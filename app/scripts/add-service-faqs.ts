async function main() {
  const payload = await getPayload({ config })

  for (const [slug, faq] of Object.entries(FAQS)) {
    const result = await payload.find({
      collection: 'pages',
      where: { slug: { equals: slug } },
      depth: 0,
      limit: 1,
      overrideAccess: true,
    })
    const page = result.docs[0]
    if (!page) {
      console.warn(`No page found for slug "${slug}", skipping`)
      continue
    }

    const layout = Array.isArray(page.layout) ? page.layout : []
    const alreadyHasFaq = layout.some((block: { blockType?: string }) => block.blockType === 'faq')
    if (alreadyHasFaq) {
      console.log(`"${slug}" already has a faq block, skipping`)
      continue
    }

    const newLayout = [...layout, { blockType: 'faq' as const, heading: faq.heading, items: faq.items }]

    console.log(`${dryRun ? '[dry-run] ' : ''}Adding faq block (${faq.items.length} items) to "${slug}"`)
    if (!dryRun) {
      await payload.update({
        collection: 'pages',
        id: page.id,
        data: { layout: newLayout },
        overrideAccess: true,
      })
    }
  }

  process.exit(0)
}

main()
